'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const helper = require('../public/action-layer');
const evidence = require('../public/prediction-evidence');
const source = fs.readFileSync(require.resolve('../public/app.js'),'utf8');
const start = source.indexOf('function renderPredictionScorecard() {');
const end = source.indexOf('async function renderDecisionLearningPanel()',start);
const valid = {id:'a',symbol:'SAFE',market:'us',source:'system',strategyVersion:'s1',resolverVersion:'daily-bar-resolver-v3',createdAt:'2026-06-01T12:00:00Z',resolvedAt:'2026-06-04T12:00:00Z',entry:100,target:112,stop:94,closePrice:112,resultPct:12,outcome:'target-hit',outcomeEvidence:'daily_bar_range',barDate:'2026-06-02',barEndAt:'2026-06-02T20:00:00Z'};
const mount = {innerHTML:''};
const sandbox = {$:()=>mount,esc:value=>String(value==null?'':value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'})[c]),JOURNAL:{predictions:[valid,{...valid,id:'loss',symbol:'LOSS',strategyVersion:'s2',outcome:'stop-hit',closePrice:94,resultPct:-6},{...valid,id:'old',symbol:'LEGACY',strategyVersion:null},{...valid,id:'bad',symbol:'BAD',resolvedAt:'2099-01-01T00:00:00Z'},{...valid,id:'amb',symbol:'AMB',outcomeEvidence:'ambiguous_bar'}]},predictionCohortFilter:'verified',window:{FinansActionLayer:helper,FinansPredictionEvidence:evidence}};
vm.runInNewContext(source.slice(start,end),sandbox);
sandbox.renderPredictionScorecard();
assert.match(mount.innerHTML,/100% \(1\/1 belirleyici\)/);
assert.match(mount.innerHTML,/0% \(0\/1 belirleyici\)/);
assert.doesNotMatch(mount.innerHTML,/50%/,'different strategies never pool success');
assert.doesNotMatch(mount.innerHTML,/<b>LEGACY<\/b>|<b>BAD<\/b>|<b>AMB<\/b>/,'archive rows are not in default performance');
assert.match(mount.innerHTML,/gerçekleşmiş net hesap getirisi değildir/);
const grouped = helper.buildPredictionCohorts(sandbox.JOURNAL);
assert.ok(mount.innerHTML.includes('value="'+encodeURIComponent(grouped.groups[0].key)+'"'),'cohort JSON is safely encoded for option attributes');
sandbox.predictionCohortFilter = grouped.groups.find(g=>g.status==='legacy').key;
sandbox.renderPredictionScorecard();
assert.match(mount.innerHTML,/<b>LEGACY<\/b>/);
assert.match(mount.innerHTML,/Arşiv isabeti · doğrulanmamış/);
sandbox.predictionCohortFilter = grouped.groups.find(g=>g.status==='invalid').key;
sandbox.renderPredictionScorecard();
assert.match(mount.innerHTML,/Hesaplanamadı — belirleyici örnek yok/);
assert.doesNotMatch(mount.innerHTML,/100% \(1\/1/,'future resolution cannot create a rate');
sandbox.predictionCohortFilter = grouped.groups.find(g=>g.status==='ambiguous').key;
sandbox.renderPredictionScorecard();
assert.match(mount.innerHTML,/Belirsiz · aynı mumda hedef ve stop/);
assert.match(mount.innerHTML,/Getiri ölçülemedi/);
assert.doesNotMatch(mount.innerHTML,/>\+12%/);
sandbox.JOURNAL.predictions = [{...valid,id:'open',outcome:'open',resolvedAt:null,closePrice:null,resultPct:null}];
sandbox.predictionCohortFilter='verified';
sandbox.renderPredictionScorecard();
assert.match(mount.innerHTML,/Hesaplanamadı — belirleyici örnek yok/);
assert.doesNotMatch(mount.innerHTML,/null%|undefined%|0% \(/);
console.log('Prediction scorecard separates methods, excludes invalid evidence, and preserves archive access');
