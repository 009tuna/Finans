'use strict';
const assert=require('node:assert/strict');
const {evaluateSignal,confirmedPivots,clusterLevels,selectTarget,netGate}=require('../src/structural-signals');
const {observation}=require('./helpers/structural-fixtures');
const o=observation(), result=evaluateSignal(o);
assert.equal(result.status,'candidate',JSON.stringify(result.reasons));
assert.equal(result.plan.setup,'A');
assert.equal(result.plan.supportEvidence.lower,100);
assert.equal(result.plan.resistanceEvidence.lower,115);
assert.notEqual(result.plan.entryZone[0],o.bars.at(-1).close,'entry is a structural region, not latest quote');
assert.deepEqual(result,evaluateSignal(structuredClone(o)),'deterministic parameters, pivots and identity');
assert.equal(evaluateSignal({...o,sourceObservedAt:'2026-01-01T00:00:00Z'}).status,'watch');
assert.equal(evaluateSignal({...o,calendar:{status:'unverified'}}).status,'watch');
assert.equal(evaluateSignal({...o,bars:o.bars.slice(-219)}).status,'watch');
const future=structuredClone(o);future.bars.push({...future.bars.at(-1),date:'2099-01-01',barStartAt:'2099-01-01T00:00:00Z',barEndAt:'2099-01-02T00:00:00Z',low:1,high:1000});
assert.equal(evaluateSignal(future).setupId,result.setupId,'future completed flags cannot leak into cut');
const pivots=[3,3,3,2,3,3,3].map((low,i)=>({date:String(i),low,high:10}));
assert.equal(confirmedPivots(pivots.slice(0,6)).length,0);
assert.equal(confirmedPivots(pivots).filter(p=>p.type==='support').length,1);
assert.equal(confirmedPivots(pivots).filter(p=>p.type==='resistance').length,0,'equal highs are not strict pivots');
const clusters=clusterLevels([{type:'support',price:100,index:0,confirmedIndex:3},{type:'support',price:100.6,index:12,confirmedIndex:15},{type:'support',price:101.2,index:24,confirmedIndex:27}],1);
assert.equal(clusters.length,1);assert.equal(clusters[0].upper,100.6,'bounded width prevents chain inflation');
assert.equal(selectTarget([{lower:102,upper:104,id:'near'},{lower:120,upper:121,id:'far'}],[100,103],1).reason,'first-resistance-overlaps');
assert.equal(netGate(100,95,102,{roundTrip:.004}).pass,false);
const extended=structuredClone(o);extended.bars.at(-1).close=150;extended.bars.at(-1).high=151;
assert.match(evaluateSignal(extended).reasons.join(),/extension/);
const invalid=structuredClone(o);invalid.bars[230].close=90;invalid.bars[230].low=89;
assert.equal(evaluateSignal(invalid).status,'watch','invalidated root cannot resurrect from old pivots');
const b=structuredClone(o);b.bars[237].close=117;b.bars[237].high=118;b.bars[237].volume=150;
b.bars[238].close=116;b.bars[238].open=116;b.bars[238].high=117;b.bars[238].low=115;
b.bars[239].close=116;b.bars[239].open=116;b.bars[239].high=117;b.bars[239].low=115;
// First resistance is the broken region; another independently confirmed overhead region is required.
for(const i of [175,195]) b.bars[i].high=145;
assert.equal(evaluateSignal(b).plan?.setup,'B',JSON.stringify(evaluateSignal(b).reasons));
const early=structuredClone(b); early.bars[237].volume=100;
assert.notEqual(evaluateSignal(early).plan?.setup,'B','breakout needs preceding 20-bar relative volume');
console.log('structural strategy OK');
