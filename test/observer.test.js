'use strict';
const assert = require('node:assert/strict');
const observer = require('../public/observer');
const scenarios = require('../public/expectation-scenarios');
const records = require('../public/structural-records');
const {makeRecord,acknowledgeRegistration,advancePaperTrade} = require('../src/paper-trade-engine');
const {evaluateSignal} = require('../src/structural-signals');
const {observation,freshBar} = require('./helpers/structural-fixtures');
const {DAY,iso} = require('../src/structural-data');
const base=observation(), pending=acknowledgeRegistration(makeRecord(evaluateSignal(base),base,base.sourceObservedAt), {revision:'qa-saved',responseAt:iso(Date.parse(base.sourceObservedAt)+1000)});
const next=Math.floor(Date.parse(base.sourceObservedAt)/DAY)*DAY+DAY, date=iso(next).slice(0,10);
const entry=(pending.plan.entryZone[0]+pending.plan.entryZone[1])/2;
function advance(bars) {
  const at=iso(next+bars.length*DAY);
  return advancePaperTrade(pending,{...base,bars:base.bars.concat(bars),sourceObservedAt:at,effectiveCutoffAt:at,generationCutoffAt:at},{preparedAt:at});
}
const filled=advance([freshBar(date,{open:entry,high:entry+.1,low:entry-.1,close:entry})]);
const closed=advance([freshBar(date,{open:entry,high:pending.plan.target+1,low:entry-.1,close:entry})]);
assert.equal(records.classifyRecord(closed).category,'verified');
const ambiguous=advance([freshBar(date,{open:entry,high:pending.plan.target+1,low:pending.plan.stop-1,close:entry})]);
const missed=advance([freshBar(date,{open:pending.plan.entryZone[1]+5})]);
const incomplete=structuredClone(filled);incomplete.evidence.status='evidence-incomplete';
const legacy={id:'old',symbol:'OLD',market:'us',source:'system',outcome:'open',createdAt:base.sourceObservedAt};
const all=[pending,filled,closed,ambiguous,missed,incomplete,legacy];
const before=JSON.stringify(all), g=observer.groups(all);
assert.equal(g.active.length,3,'pending, filled and evidence-blocked open states stay visible');
assert.equal(g.history.length,3,'closed ambiguous and missed records stay in history');
assert.equal(g.score.verified,1,'ambiguous, incomplete and old results never inflate the denominator');
assert.equal(g.legacy.length,1);
assert.match(observer.dashboard(all,[],{tab:'active'}),/Giriş bekleniyor|Sanal işlem açık/);
assert.match(observer.dashboard(all,[],{tab:'history'}),/Doğrulanmış kapanış|% net/);
assert.doesNotMatch(observer.summary(all,false),/%0|0 aktif/,'outage is not a zero sample');
assert.doesNotMatch(observer.dashboard(all,[],{},false),/OLD|BTC/,'unverified read is not a current ledger');
assert.match(observer.dashboard([],[]),/Henüz aktif yapısal sinyal yok/);
const asset={market:'crypto',symbol:'BTC',analysis:{score:85},decision:{structural:{reasons:['extension-gate']}}};
assert.match(observer.task(asset,[]).reason,/fazla uzamış/);
assert.match(observer.rationale(asset,[]),/fazla uzamış/);
assert.doesNotMatch(observer.rationale(asset,all),/<form|textarea|Tez notunu yaz/);
const bad=structuredClone(pending);bad.symbol='<img src=x onerror=1>';
assert.doesNotMatch(observer.dashboard([bad]),/<img/);
const malformed={id:'broken',strategyVersion:records.STRATEGY,source:'system',market:'crypto',symbol:'QA-BROKEN'};
assert.match(observer.dashboard([malformed]),/Sabit planın alanları eksik/);
assert.doesNotThrow(() => observer.dashboard([malformed],[],{tab:'performance'}));
assert.equal(JSON.stringify(all),before,'the reading surface never rewrites frozen records');
const payroll={metric:'us_nonfarm_payroll_change',unit:'thousand_jobs',pointEstimate:250,consensus:210,available:true};
assert.equal(scenarios.build(payroll).direction,1);
assert.match(scenarios.build(payroll).rows[0].text,/baskı/);
assert.equal(scenarios.build({...payroll,pointEstimate:210}).direction,0);
assert.match(scenarios.build({...payroll,pointEstimate:210}).rows[0].text,/sürpriz yok/);
assert.match(scenarios.build({...payroll,pointEstimate:100}).rows[0].text,/büyüme kaygısı/);
assert.match(scenarios.build({...payroll,consensus:null}).rows[0].text,/doğrulanamadı/);
assert.doesNotMatch(scenarios.html({...payroll,consensus:null}),/Veri [<>=] 0/);
assert.equal(scenarios.build({...payroll,available:false}).model,null,'an abstention cannot be a model estimate');
assert.equal(scenarios.build({...payroll,metric:'eps'}),null,'monthly macro rules cannot leak into earnings');
for (const metric of ['us_cpi_headline_mom_sa','us_cpi_core_mom_sa','us_cpi_headline_yoy_nsa','us_cpi_core_yoy_nsa']) {
  assert.match(scenarios.html({metric,unit:'percent',pointEstimate:.3,consensus:.2}),/Enflasyon beklenenden yüksek/,'canonical CPI metric ids must be supported');
}
const opinion={eventId:'release',sourceIds:['src'],condition:'Condition',impact:'Impact',invalidation:'Counter evidence',horizon:'1 day',market:'us'};
assert.match(scenarios.html({...payroll,eventId:'release'},{scenarios:[opinion],sources:new Map([['src',{url:'https://example.com/source',title:'Fixture source'}]])}),/Modelin bu açıklamaya özel kaynaklı senaryoları/);
assert.doesNotMatch(scenarios.html({...payroll,eventId:'another'},{scenarios:[opinion],sources:new Map([['src',{url:'https://example.com/source'}]])}),/Fixture source/,'another release cannot lend its scenario');
assert.doesNotMatch(scenarios.html({...payroll,eventId:'release'},{scenarios:[opinion],sources:new Map([['src',{url:'javascript:alert(1)'}]])}),/href="javascript/);
assert.match(scenarios.html(payroll,{historical:true}),/kayıt anındaki/);
globalThis.ExpectationScenarios=scenarios;
const research=require('../public/research');
const html=research.expectationsHtml({generatedAt:'2026-10-01T06:00:00Z',forecasts:[{...payroll,market:'us',period:'2026-09',scheduledAt:'2026-10-02T12:30:00Z',sourceIds:[],rationale:'Fixture'}],forecastAbstentions:[],sources:[]},{now:'2026-10-01T12:00:00Z',compact:true});
assert.match(html,/Modelin beklediği gibi gelirse/,'the primary compact expectation view includes the matrix');
delete globalThis.ExpectationScenarios;
console.log('Observer lifecycle, denominator, read failure, immutable rationale and macro comparison tests passed.');
