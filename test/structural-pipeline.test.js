'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {collectObservations,applyStructuralDecisions}=require('../src/structural-pipeline');
const {replayObservations}=require('../src/structural-replay');
const {observation}=require('./helpers/structural-fixtures');
const {evaluateSignal}=require('../src/structural-signals');
const {makeRecord,acknowledgeRegistration}=require('../src/paper-trade-engine');
async function main(){
  const o=observation(),r=acknowledgeRegistration(makeRecord(evaluateSignal(o),o,o.sourceObservedAt),{revision:'fixture',responseAt:o.sourceObservedAt});
  const {completedIndicators}=require('../src/fetch-all');
  const {computeIndicators}=require('../src/indicators');
  const source={dates:o.bars.map(b=>b.date),sourceTimestamps:o.bars.map(b=>b.barStartAt),closes:o.bars.map(b=>b.close),highs:o.bars.map(b=>b.high),lows:o.bars.map(b=>b.low),volumes:o.bars.map(b=>b.volume),calendar:o.calendar,technicalData:{fetchedAt:o.sourceObservedAt}};
  const withDeveloping=structuredClone(source);
  for(const key of ['dates','sourceTimestamps','closes','highs','lows','volumes']) withDeveloping[key].push(key==='dates'?o.sourceObservedAt.slice(0,10):key==='sourceTimestamps'?o.sourceObservedAt.slice(0,10)+'T00:00:00Z':99999);
  assert.deepEqual(completedIndicators(withDeveloping,'crypto',Date.parse(o.sourceObservedAt)),computeIndicators(source),'production indicators never consume developing daily prices');
  const snapshot={generatedAt:o.sourceObservedAt,crypto:[{market:'crypto',symbol:'BTC',currency:'USD',price:999,analysis:{score:99,label:'GUCLU AL'},decision:{trade:{entry:999,target:1200,stop:900}}}],us:[],bist:[]};
  applyStructuralDecisions(snapshot,{predictions:[r]},[o]);
  assert.equal(snapshot.crypto[0].decision.trade.entry,null,'unfilled signal has no actual entry');
  assert.deepEqual(snapshot.crypto[0].decision.trade.entryZone,r.plan.entryZone);
  assert.equal(snapshot.crypto[0].decision.trade.currency,'USDT','spot USD cannot restate frozen USDT plan');
  assert.equal(snapshot.crypto[0].decision.structuralRecord.id,r.id);
  assert.equal(snapshot.structural.scorecard.winRate,null);
  const {hydrateStructuralSnapshot,readStructuralSnapshot}=require('../src/structural-reader');
  const old={...snapshot,crypto:[{market:'crypto',symbol:'BTC',decision:{trade:{available:true,entry:999,target:1200,stop:900}}}]};
  assert.equal(hydrateStructuralSnapshot(old,{predictions:[]}).crypto[0].decision.trade.available,false,'old snapshot cannot revive latest-price ATR signals');
  assert.equal(hydrateStructuralSnapshot(old,{predictions:[r]}).crypto[0].decision.trade.predictionId,r.id,'journal receipt remains visible when snapshot publication failed');
  await assert.rejects(()=>readStructuralSnapshot({readSnapshot:async()=>old,readJournal:async()=>{throw Error('journal unavailable');}}),/journal unavailable/);
  let requests=0;
  const failedSpot=await collectObservations({}, {predictions:[r,r]},o.sourceObservedAt,{fetchCryptoSeries:async pair=>{requests++;assert.equal(pair,'BTCUSDT');throw Error('source down');}});
  assert.equal(requests,1,'frozen source pair fetched once even without CoinGecko spot');
  assert.equal(failedSpot.length,1);assert.equal(failedSpot[0].status,'evidence-incomplete');
  const replay=replayObservations([o]);assert.equal(replay.kind,'historical-simulation');assert.equal(replay.records[0].source,'historical-simulation');assert.equal(replay.scorecard.winRate,null);
  assert.equal(replay.records[0].execution.registrationRevision,null,'historical simulation cannot fabricate a live CAS receipt');
  assert.match(replay.limitations.join(),/survivorship/);
  const fetch=fs.readFileSync(require.resolve('../src/fetch-all'),'utf8');
  assert.ok(!fetch.includes('recordPrediction('),'legacy current-price recording removed from production');
  assert.ok(fetch.includes('processStructuralObservations('));
  assert.ok(fetch.indexOf('processStructuralObservations(')<fetch.indexOf('await saveSnapshot(snapshot)'),'persisted journal before snapshot publication');
  console.log('shared structural pipeline and replay OK');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
