'use strict';
const assert = require('node:assert/strict');
const {normalizeObservation, expectedSessions} = require('../src/structural-data');
const {normalizeSeries} = require('../src/yahoo');
const {dailySeries, normalizeKlines, validateBars} = require('../src/crypto-market-data');
const {completedCryptoHistory} = require('../src/daily-history');
const start = Date.parse('2026-09-01T00:00:00Z'), day=86400000;
const calendar={provider:'binance',interval:'1d',timeZone:'UTC',basis:'binance_klines_default_timezone'};
const raw=[0,1,2].map(i=>[start+i*day,'100','110','90','105','12',start+(i+1)*day-1]);
const series={...dailySeries(normalizeKlines(raw),calendar), technicalData:{fetchedAt:'2026-09-03T12:00:00Z'}};
assert.deepEqual(series.opens,[100,100,100]);
assert.deepEqual(series.openVerified,[true,true,true]);
const observation=normalizeObservation({series,market:'crypto',symbol:'BTC',sourceSymbol:'BTCUSDT',provider:'binance',currency:'USDT',priceBasis:'unadjusted'},'2026-09-03T13:00:00Z');
assert.equal(observation.bars[2].completed,false);
assert.equal(observation.bars[2].openVerified,true,'developing bar can prove its open but not its range outcome');
assert.equal(observation.effectiveCutoffAt,'2026-09-03T12:00:00.000Z');
assert.equal(observation.calendar.status,'verified');
assert.equal(expectedSessions(observation,'2026-09-02T12:00:00Z','2026-09-04T12:00:00Z').length,2);
assert.deepEqual(completedCryptoHistory(series,Date.parse('2026-09-04T12:00:00Z')).series.opens,[100,100]);
assert.match(normalizeObservation({series:{...series,opens:[100]},market:'crypto',provider:'binance',currency:'USDT'},'2026-09-03T13:00:00Z').reasons.join(),/array-alignment/);
assert.match(normalizeObservation({series,market:'crypto',provider:'binance',currency:'USD'},'2026-09-03T13:00:00Z').reasons.join(),/currency/);
const gap={...series}; for(const key of Object.keys(gap)) if(Array.isArray(gap[key])) gap[key]=[gap[key][0],gap[key][2]];
assert.deepEqual(normalizeObservation({series:gap,market:'crypto',provider:'binance',currency:'USDT'},'2026-09-03T13:00:00Z').coverage.missingDates,['2026-09-02']);
const legacy=validateBars([{time:start/1000,open:105,high:110,low:90,close:105,volume:12,openVerified:false,sourceProvenance:'legacy-imputed'}]);
assert.equal(dailySeries(legacy,calendar).openVerified[0],false,'cache roundtrip cannot promote imputed opens');
const conflicting=normalizeKlines([raw[0],[...raw[0].slice(0,4),'106',...raw[0].slice(5)]]);
assert.equal(conflicting[0].sourceConflict,true,'duplicate source observations are not silently trusted');
const equity=normalizeSeries({chart:{result:[{meta:{exchangeTimezoneName:'America/New_York',currency:'USD',currentTradingPeriod:{regular:{start:Date.parse('2026-09-02T13:30:00Z')/1000,end:Date.parse('2026-09-02T20:00:00Z')/1000}}},timestamp:[start/1000,(start+day+15*3600000)/1000],indicators:{quote:[{open:[99,null],close:[100,101],high:[110,111],low:[90,91],volume:[12,13]}]}}]}},'AAPL',{observedAt:'2026-09-02T21:00:00Z'});
assert.deepEqual(equity.series.opens,[99,null]);
assert.deepEqual(equity.series.openVerified,[true,false]);
assert.equal(equity.series.barStartAt[0],null,'daily bar label cannot manufacture an opening instant');
assert.equal(equity.series.barStartAt[1],'2026-09-02T13:30:00.000Z');
assert.equal(equity.series.timestampRole,'bar_label');
assert.match(normalizeObservation({series:equity.series,market:'us',provider:'yahoo',currency:'USD'},'2026-09-02T22:00:00Z').reasons.join(),/calendar-unverified/);
console.log('structural source evidence OK');
