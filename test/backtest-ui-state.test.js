'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('public/app.js','utf8');
const story = {innerHTML:''};
let insight;
const context = vm.createContext({$:()=>story, window:{FinansInsights:{explainBacktest:()=>insight}}, esc:String, fmtPct:n=>String(n)+'%', fmtPrice:String});
const start=source.indexOf('function renderBacktestStory(');
vm.runInContext(source.slice(start,source.indexOf('function drawBacktestChart(',start)),context);
const result={symbol:'AAPL',trades:[],strategyReturn:0,bhReturn:5,initialCapital:10000,finalCapital:10000,buyThreshold:100,sellThreshold:45,firstHalfReturn:0,secondHalfReturn:0};
insight={closedTrades:0,winRate:0,worksWhen:'Alım yok',breaksWhen:'Eşiği kontrol edin',maxDrawdown:0,headlineTone:'warn'};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/İsabet hesaplanamadı · kapanan işlem yok/);
assert.doesNotMatch(story.innerHTML,/İsabet %0|daha güvenilir/);
assert.match(story.innerHTML,/kapanan işlem yok; strateji başarısı ölçülemiyor/);
result.trades=[{type:'BUY'},{type:'SELL',pnlPct:1}];
result.firstHalfReturn=1;result.secondHalfReturn=2;
insight={...insight,closedTrades:1,winRate:100};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/İsabet %100 · 1 kapanan işlem/);
assert.match(story.innerHTML,/tek başına güvenilirlik kanıtı değildir/);
console.log('Backtest sample and confidence presentation tests passed');
