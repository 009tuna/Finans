assert.match(story.innerHTML,/Kaynak gözlemi: 2026-10-02T20:05:00Z/);
assert.match(story.innerHTML,/Kullanılan kapanış kesiti: 2026-10-02T20:04:00Z/);
assert.match(story.innerHTML,/Tamamlanmış 250 günlük gözlem; açık 1, kapanışı doğrulanamayan 0/);
assert.match(story.innerHTML,/<details class="bt-method-details"><summary>Yöntem ve risk ölçüleri/);
assert.doesNotMatch(story.innerHTML,/<details[^>]*\bopen\b/,'supplemental method detail should not crowd the result on first render');
result.history.completion.completedObservations=null;
context.renderBacktestStory(result);
assert.match(story.innerHTML,/Tamamlanmış bilinmiyor günlük gözlem/);
const displayStart = source.indexOf('function displayBacktestResults(');
const displayContext = vm.createContext({backtestResult:{previous:true}});
vm.runInContext(source.slice(displayStart,source.indexOf('function renderBacktestStory(',displayStart)),displayContext);
for (const invalid of [{}, {...result,equityCurve:[]}, {...result,strategyReturn:NaN}, {...result,equityCurve:[{price:0,total:10000}]}]) {
  assert.throws(()=>displayContext.displayBacktestResults(invalid),/Geçerli sermaye eğrisi/);
  assert.equal(displayContext.backtestResult.previous,true,'hatalı sonuç önceki başarılı sonucu ezemez');
}
