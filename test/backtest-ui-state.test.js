'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('public/app.js','utf8');
const story = {innerHTML:''};
let insight;
const context = vm.createContext({$:()=>story, window:{FinansInsights:{explainBacktest:()=>insight}}, esc:String, fmtPct:n=>String(n)+'%', fmtPrice:String, fullTimestamp: value => value || 'bilinmiyor'});
const start=source.indexOf('function renderBacktestStory(');
vm.runInContext(source.slice(start,source.indexOf('function drawBacktestChart(',start)),context);
const result={symbol:'AAPL',trades:[],strategyReturn:0,bhReturn:5,initialCapital:10000,finalCapital:10000,buyThreshold:100,sellThreshold:45,firstHalfReturn:0,secondHalfReturn:0};
insight={closedTrades:0,measuredClosedTrades:0,winRate:null,worksWhen:'Alım yok',breaksWhen:'Eşiği kontrol edin',maxDrawdown:0,headlineTone:'warn'};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/İsabet hesaplanamadı · kapanan işlem yok/);
assert.doesNotMatch(story.innerHTML,/İsabet %0|daha güvenilir/);
assert.match(story.innerHTML,/kapanan işlem yok; strateji başarısı ölçülemiyor/);
result.trades=[{type:'BUY'},{type:'SELL',pnlPct:1.1,netPnlPct:1}];
result.firstHalfReturn=1;result.secondHalfReturn=2;
insight={...insight,closedTrades:1,measuredClosedTrades:1,winRate:100};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/Kârlı işlem %100 · 1 net sonuç/);
assert.match(story.innerHTML,/tek başına güvenilirlik kanıtı değildir/);
result.firstHalfReturn=0;result.secondHalfReturn=-1;
context.renderBacktestStory(result);
assert.match(story.innerHTML,/iki yarıda getirinin yönü farklı/);
result.trades=[{type:'BUY'},{type:'SELL',pnlPct:0.05,netPnlPct:-0.05}];
insight={...insight,winRate:0};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/Kârlı işlem %0/);
assert.match(story.innerHTML,/1 işlemin 0 tanesi maliyetler sonrası kârlı/);
result.bhReturn=null;
insight={...insight,measuredClosedTrades:0,winRate:null,maxDrawdown:null};
context.renderBacktestStory(result);
assert.match(story.innerHTML,/Al-tut karşılaştırması hesaplanamadı/);
assert.doesNotMatch(story.innerHTML,/yüzde puan|Max düşüş %null|Kârlı işlem %null/);
assert.match(story.innerHTML,/Düşüş hesaplanamadı/);
result.history = {completion:{observedAt:'2026-10-02T20:05:00Z',effectiveCutoffAt:'2026-10-02T20:04:00Z',completedObservations:250,excludedOpenBars:1,excludedUnverifiedBars:0}};
