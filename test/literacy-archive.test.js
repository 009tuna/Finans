'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('public/app.js','utf8');
const element = {innerHTML:''};
const context = vm.createContext({$:()=>element, esc:value=>String(value).replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]))});
const start = source.indexOf('function renderTipsArchive(');
vm.runInContext(source.slice(start,source.indexOf('window.submitQuizAnswer',start)),context);
context.renderTipsArchive(null);
assert.match(element.innerHTML,/alınamadı/);
assert.doesNotMatch(element.innerHTML,/Henüz arşivlenmiş/);
context.renderTipsArchive([]);
assert.match(element.innerHTML,/Henüz arşivlenmiş/);
context.renderTipsArchive([{date:'2026-06-02',title:'Beklenti ne anlatır?',body:'Normal Türkçe metin.'},{date:'2026-06-03',title:'kataliz?r',body:'Bozulmu? eski metin <script>unsafe</script>'}]);
assert.equal((element.innerHTML.match(/<details class="literacy-archive-entry">/g)||[]).length,2);
assert.doesNotMatch(element.innerHTML,/<details[^>]*\sopen|<script>/);
assert.ok(element.innerHTML.indexOf('2026-06-02') < element.innerHTML.indexOf('literacy-unreadable-archive'), 'readable notes precede the separate damaged archive');
assert.ok(element.innerHTML.indexOf('literacy-unreadable-archive') < element.innerHTML.indexOf('2026-06-03'), 'damaged original remains reachable inside its group');
assert.match(element.innerHTML,/Karakter kaybı olan eski not/);
assert.match(element.innerHTML,/kataliz\?r/,'orijinal kayıt değiştirilmeden korunur');
assert.match(element.innerHTML,/Beklenti ne anlatır\?/,'normal soru işareti karakter kaybı değildir');
assert.match(element.innerHTML,/güncel beklenti olarak okunmamalı/);
context.renderTipsArchive([{date:'2026-06-02',title:'İlk not',body:'Metin.'},{date:'2026-06-04',title:'Yeni not',body:'Metin.'},{date:'2026-06-03',title:'bozuk?not',body:'Metin.'},{date:'2026-06-05',title:'yeni?arşiv',body:'Metin.'}]);
assert.ok(element.innerHTML.indexOf('2026-06-04') < element.innerHTML.indexOf('2026-06-02'), 'readable group remains newest first');
assert.ok(element.innerHTML.indexOf('2026-06-05') < element.innerHTML.indexOf('2026-06-03'), 'damaged archive remains newest first');
context.renderTipsArchive([null,{title:'Eksik'}]);
assert.match(element.innerHTML,/okunabilir not gösterilemiyor/);
console.log('Literacy archive: closed entries, truthful failure/empty states, original encoding and safe text passed');
