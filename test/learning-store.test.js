'use strict';
const assert = require('node:assert/strict');
const {canonicalHash,validateLearningExample} = require('../src/learning-contract');
const {appendLearningRecords,readLearningRecords,shardKey} = require('../src/learning-store');
const {memoryDatabase,example} = require('./learning-fixtures');
(async()=>{
  assert.equal(canonicalHash({b:1,a:[2,3]}),canonicalHash({a:[2,3],b:1}));
  for(const bad of [NaN,Infinity,undefined,()=>1,new Date(),{a:undefined},[,1]]) assert.throws(()=>canonicalHash(bad));
  const cycle={}; cycle.a=cycle; assert.throws(()=>canonicalHash(cycle));
  assert.throws(()=>validateLearningExample(example({schemaVersion:2})));
  assert.throws(()=>validateLearningExample(example({sourceObservedAt:'2027-01-01T00:00:00Z'})));
  const db=memoryDatabase(), first=example();
  await appendLearningRecords({examples:[first]},db);
  assert.equal((await appendLearningRecords({examples:[first]},db)).existing,1);
  await assert.rejects(appendLearningRecords({examples:[{...first,cohort:'another',createdAt:'2026-02-02T10:00:00Z'}]},db),/identity_conflict/);
  await Promise.all([appendLearningRecords({examples:[example({id:'two'})]},db),appendLearningRecords({examples:[example({id:'three',createdAt:'2026-02-02T00:00:00Z'})]},db)]);
  assert.equal((await readLearningRecords({asOf:'2026-03-01T00:00:00Z'},db)).records.length,3);
  assert.notEqual(shardKey('example',first),shardKey('example',{...first,createdAt:'2026-02-01T00:00:00Z'}));
  const full=memoryDatabase(), key=shardKey('example',first);
  full.rows.set(key,{revision:'seed',value:{schemaVersion:1,refs:Array.from({length:1000},(_,i)=>({id:String(i),hash:'b'.repeat(64)}))}});
  await assert.rejects(appendLearningRecords({examples:[first]},full),/capacity/);
  const interrupted=memoryDatabase(), cas=interrupted.compareAndSetCache;
  let fail=true; interrupted.compareAndSetCache=async(k,v,r)=>{if(fail&&k==='learning:index:v1'){fail=false;throw Error('timeout');}return cas(k,v,r);};
  await assert.rejects(appendLearningRecords({examples:[first]},interrupted),/timeout/);
  await appendLearningRecords({examples:[first]},interrupted);
  assert.equal((await readLearningRecords({},interrupted)).records.length,1);
  await assert.rejects(readLearningRecords({}, {getCache:async()=>{throw Error('timeout');}}),/timeout/);
  const corrupt=memoryDatabase(); corrupt.rows.set('learning:index:v1',{revision:'x',value:{shards:'bad'}});
  await assert.rejects(readLearningRecords({},corrupt),/corrupt/);
  console.log('learning-store: PASS');
})().catch(e=>{console.error(e);process.exitCode=1;});
