'use strict';
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const source = fs.readFileSync('public/app.js', 'utf8');
const start = source.indexOf('function overviewMarketStats(');
const end = source.indexOf('\nfunction renderOverviewPortfolioSummary', start);
const context = vm.createContext({});
vm.runInContext(source.slice(start, end), context);
const item = (score, changePct, tone = 'hold') => ({ analysis: { score, tone }, changePct });
const snapshot = { us: [item(100, 2, 'buy'), item(80, -1)], bist: [item(20, 0), item(0, null), {__error:'source failed',analysis:{score:99},changePct:10}], crypto: [{ price: 5, changePct: null }] };
const previous = JSON.stringify(snapshot);
const rows = context.overviewMarketStats(snapshot);
assert.equal(rows[0].avg, 90);
assert.equal(rows[1].avg, 10, 'US scores never lift BIST average');
assert.equal(rows[1].changeCount, 1, 'zero change is known; null and failed source are excluded');
assert.equal(rows[1].gainers, 0);
assert.equal(rows[1].scored, 2, 'zero score is observed, not missing');
assert.equal(rows[1].total, 3);
assert.equal(rows[1].failed, 1);
assert.equal(rows[2].avg, null, 'unscored market never gets a neutral-looking zero');
assert.equal(rows[2].changeCount, 0);
assert.equal(rows[0].buys, 1);
assert.equal(JSON.stringify(snapshot), previous);
assert.ok(context.overviewMarketStats(null).every(row => row.total === 0 && row.avg === null));
assert.equal(context.overviewMarketStats({us:[item('85',4),item(Infinity,3),item(110,2),item(-10,1)]})[0].scored,0);
console.log('Per-market averages, honest denominators, zero values, missing coverage and immutable input passed');
